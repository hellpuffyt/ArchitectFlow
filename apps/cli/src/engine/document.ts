// Architecture document generation (spec section 4, A-G). Renders a Markdown
// report from the model, facts and evidence. Observed facts are stated plainly and
// cited; recommendations live in their own clearly-labelled subsections so the
// reader never confuses inference with implementation (spec sections 4, 7).

import { scrubSecrets } from "./privacy.ts";
import type { AnalysisFacts, ArchitectureDocument, EvidenceRecord } from "../types.ts";

function fence(mermaid: string): string {
  return "```mermaid\n" + mermaid + "\n```";
}
function cite(e: EvidenceRecord | undefined): string {
  if (!e || !e.evidence.length) return "_no direct evidence_";
  return e.evidence.map((ev) => {
    const loc = ev.lineStart ? `${ev.path}:${ev.lineStart}${ev.lineEnd ? "-" + ev.lineEnd : ""}` : ev.path;
    return `\`${loc}\`${ev.symbol ? ` (${ev.symbol})` : ""}`;
  }).join(", ");
}
const CONF_BADGE: Record<string, string> = { verified: "✅ verified", inferred: "🟡 inferred", recommendation: "💡 recommendation", unknown: "❔ unknown" };

export function generateMarkdown(doc: ArchitectureDocument, facts: AnalysisFacts, evidence: EvidenceRecord[], diagrams: Record<string, string>, generatedAt: string): string {
  const byId = new Map(evidence.map((e) => [e.elementId, e]));
  const L: string[] = [];
  const S = facts.stack;

  L.push(`# System Architecture — ${scrubSecrets(facts.root.split("/").pop() ?? "repository")}`);
  L.push("");
  L.push(`> Generated by **ArchitectFlow** from source on ${generatedAt}. Every claim is traceable to the code cited beside it. Confidence: ✅ verified (direct evidence) · 🟡 inferred · 💡 recommendation · ❔ unknown/externally configured.`);
  L.push("");
  L.push(`**Scope analysed:** ${facts.files.length} files · ${S.languages.map((l) => `${l.name} (${l.files})`).join(", ")} · ${facts.skipped.length} skipped (sensitive/vendored/too large).`);
  L.push("");

  // A. System overview
  L.push("## A. System overview");
  L.push("");
  L.push(`- **Purpose:** ${scrubSecrets(doc.vision)}`);
  L.push(`- **Architectural style:** ${describeStyle(facts)}`);
  L.push(`- **Technology stack:** ${doc.technology_preferences.join(", ") || "n/a"}`);
  L.push(`- **Package managers / build:** ${[...S.packageManagers, ...S.buildSystems].join(", ") || "n/a"}`);
  L.push(`- **Workspaces:** ${S.monorepo ? `monorepo, ${S.workspaces.length}` : "single package"} — ${S.workspaces.map((w) => `\`${w.rel || "."}\` (${w.name})`).slice(0, 12).join(", ")}`);
  L.push("");
  L.push("### Frameworks (declared)");
  for (const f of S.frameworks) L.push(`- **${f.name}** — ${cite({ elementId: "", elementKind: "claim", label: f.name, confidence: "verified", evidence: [f.evidence] })}`);
  if (!S.frameworks.length) L.push("- _none detected from manifests_");
  L.push("");
  L.push("### System context"); L.push(""); L.push(fence(diagrams.context ?? "")); L.push("");

  // B. Architecture
  L.push("## B. Architecture");
  L.push("");
  L.push("### Container view (C4 level 2)"); L.push(""); L.push(fence(diagrams.container ?? "")); L.push("");
  L.push("### Components / modules (from traced imports)"); L.push(""); L.push(fence(diagrams.component ?? "")); L.push("");
  L.push("### Service dependencies"); L.push(""); L.push(fence(diagrams["service-dependencies"] ?? "")); L.push("");
  L.push("### Components table");
  L.push("");
  L.push("| Component | Type | Technology | Confidence | Source |");
  L.push("|---|---|---|---|---|");
  for (const n of doc.nodes) {
    const e = byId.get(n.id);
    L.push(`| ${n.label} | \`${n.type}\` | ${n.technology ?? ""} | ${CONF_BADGE[e?.confidence ?? "unknown"]} | ${cite(e)} |`);
  }
  if (!doc.nodes.length) L.push("| _no components_ | | | | |");
  L.push("");

  // C. Data architecture
  L.push("## C. Data architecture");
  L.push("");
  L.push(`- **Entities:** ${doc.database.entities.length} · **Migrations:** ${facts.migrations.map((m) => `${m.tool} (${m.count})`).join(", ") || "none detected"}`);
  L.push("");
  L.push("### Entity–relationship"); L.push(""); L.push(fence(diagrams["entity-relationship"] ?? "")); L.push("");
  for (const ent of doc.database.entities.slice(0, 60)) {
    const e = byId.get(ent.id);
    L.push(`#### \`${ent.name}\` — ${cite(e)}`);
    L.push("");
    L.push("| Field | Type | PK | Null | Unique | FK |");
    L.push("|---|---|---|---|---|---|");
    for (const f of ent.fields.slice(0, 50)) {
      const fk = f.foreign_key ? doc.database.entities.find((x) => x.id === f.foreign_key!.entity_id)?.name ?? "" : "";
      L.push(`| ${f.name} | ${f.type} | ${f.primary_key ? "•" : ""} | ${f.nullable ? "•" : ""} | ${f.unique ? "•" : ""} | ${fk} |`);
    }
    L.push("");
  }

  // D. Application flows
  L.push("## D. Application flows");
  L.push("");
  L.push("### Authentication (inferred)"); L.push(""); L.push(fence(diagrams["auth-sequence"] ?? "")); L.push("");
  L.push("### Data flow"); L.push(""); L.push(fence(diagrams["data-flow"] ?? "")); L.push("");
  L.push("### API surface");
  L.push("");
  if (doc.api.endpoints.length) {
    L.push("| Method | Path | Auth | Framework | Source |");
    L.push("|---|---|---|---|---|");
    for (const ep of doc.api.endpoints.slice(0, 200)) {
      const e = byId.get(ep.id);
      L.push(`| ${ep.method} | \`${ep.path}\` | ${ep.auth} | ${(ep.summary ?? "").replace(" route", "")} | ${cite(e)} |`);
    }
    if (doc.api.endpoints.length > 200) L.push(`| … | ${doc.api.endpoints.length - 200} more | | | |`);
  } else {
    L.push("_No HTTP routes were extracted. The API may use a framework not yet supported by the extractor, or be defined dynamically._");
  }
  L.push("");

  // E. Infrastructure
  L.push("## E. Infrastructure");
  L.push("");
  L.push("### Deployment"); L.push(""); L.push(fence(diagrams.deployment ?? "")); L.push("");
  if (facts.infra.length) {
    L.push("| Kind | Name | Source |");
    L.push("|---|---|---|");
    for (const i of facts.infra) L.push(`| ${i.kind} | ${i.name}${i.detail ? ` — ${i.detail}` : ""} | \`${i.evidence.path}\` |`);
  } else L.push("_No containerisation, CI, or hosting configuration was found in the repository._");
  L.push("");

  // F. Security architecture
  L.push("## F. Security architecture");
  L.push("");
  L.push("**Observed (facts):**");
  for (const a of facts.auth) L.push(`- ${a.mechanism} — ${cite({ elementId: "", elementKind: "claim", label: a.mechanism, confidence: "verified", evidence: [a.evidence] })}${a.roles.length ? ` · roles: ${a.roles.join(", ")}` : ""}`);
  if (!facts.auth.length) L.push("- No authentication/authorization implementation detected in scanned source.");
  L.push(`- Secret handling: ${facts.skipped.filter((s) => /sensitive/.test(s.reason)).length} sensitive file(s) present and intentionally **not read** by the analyzer.`);
  L.push("");
  L.push("**Recommendations (not implementation facts):**");
  L.push("- Confirm every state-changing endpoint enforces authN/authZ; the extractor marks auth by heuristic and may miss middleware-level enforcement.");
  if (!facts.infra.some((i) => i.kind === "caddy" || i.kind === "nginx")) L.push("- No TLS-terminating proxy detected in-repo; verify transport encryption is enforced at the deployment edge.");
  L.push("- Verify secrets are injected from the environment / a secrets manager, never committed (sensitive files were not inspected).");
  L.push("");

  // G. Architecture assessment
  L.push("## G. Architecture assessment");
  L.push("");
  L.push("_These are inferences and recommendations, separated from the observed facts above._");
  L.push("");
  const singlePoints = doc.nodes.filter((n) => n.type === "database").map((n) => n.label);
  L.push(`- **Single points of failure (candidate):** ${singlePoints.join(", ") || "none obvious from the model"} — confirm replication/backup.`);
  L.push(`- **Scalability:** ${doc.nodes.some((n) => n.type === "worker") ? "background workers present (async offload)" : "no async worker tier detected"}; ${doc.nodes.some((n) => n.type === "cache") ? "a cache is present" : "no cache tier detected"}.`);
  L.push(`- **Maintainability:** ${S.monorepo ? `monorepo with ${S.workspaces.length} workspaces` : "single package"}; ${facts.imports.filter((i) => i.toRel).length} internal import edges traced.`);
  L.push(`- **Observability:** ${doc.nodes.some((n) => n.type === "observability") ? "instrumentation dependency detected" : "no observability stack detected in dependencies"}.`);
  L.push("");

  // Open questions
  if (doc.open_questions.length) {
    L.push("## Open questions / unknowns");
    L.push("");
    for (const qn of doc.open_questions) L.push(`- ❔ ${qn}`);
    L.push("");
  }

  L.push("---");
  L.push(`_ArchitectFlow local analysis. ${evidence.length} elements, each with source evidence. No source was uploaded; no scripts were executed._`);
  return scrubSecrets(L.join("\n"));
}

function describeStyle(facts: AnalysisFacts): string {
  const hasFe = facts.entryPoints.some((e) => e.kind === "frontend");
  const hasBe = facts.entryPoints.some((e) => e.kind === "backend");
  const hasWorker = facts.entryPoints.some((e) => e.kind === "worker");
  if (facts.stack.monorepo && hasFe && hasBe) return "Monorepo with separate frontend and backend services" + (hasWorker ? " and background workers" : "");
  if (hasFe && hasBe) return "Client–server web application";
  if (hasBe) return "Backend service / API";
  if (hasFe) return "Frontend application";
  return "Library or tool (no long-running service entry detected)";
}
