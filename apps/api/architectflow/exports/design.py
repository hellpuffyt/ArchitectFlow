"""Design exports: tokens (JSON + CSS variables), design spec, page flow, route map,
component inventory."""

from __future__ import annotations

import itertools
import json
from collections import Counter

from ..prompts.design_sections import active_theme, design_section, pages_section
from ..schema import ArchitectureDocument, Theme, walk
from .text import ident, md_cell, mermaid_label


def tokens_json(doc: ArchitectureDocument) -> str:
    themes = [t.model_dump() for t in doc.design.themes]
    return (
        json.dumps(
            {
                "format": "architectflow-design-tokens",
                "version": 1,
                "active_theme_id": doc.design.active_theme_id,
                "themes": themes,
            },
            indent=2,
        )
        + "\n"
    )


def _css_block(selector: str, theme: Theme, palette: str) -> list[str]:
    p = getattr(theme, palette)
    lines = [f"{selector} {{"]
    lines += [f"  --color-{k.replace('_', '-')}: {v};" for k, v in p.model_dump().items()]
    return [*lines, "}"]


def tokens_css(doc: ArchitectureDocument) -> str:
    t = active_theme(doc)
    if t is None:
        return "/* No theme saved. */\n"
    ty, r = t.typography, t.radii
    space = {"compact": 0.85, "comfortable": 1.0, "spacious": 1.25}[t.spacing.density]
    shadow = {
        "none": "none",
        "subtle": "0 1px 2px rgb(0 0 0 / .08)",
        "medium": "0 4px 14px rgb(0 0 0 / .14)",
        "strong": "0 10px 30px rgb(0 0 0 / .25)",
    }[t.elevation.shadow]
    base = [
        ":root {",
        f"  --font-heading: {ty.heading_font};",
        f"  --font-body: {ty.body_font};",
        f"  --font-mono: {ty.mono_font};",
        f"  --font-size-base: {ty.base_size}px;",
        f"  --font-scale: {ty.scale_ratio};",
        f"  --line-height: {ty.line_height};",
        f"  --font-weight-heading: {ty.heading_weight};",
        f"  --font-weight-body: {ty.body_weight};",
        f"  --space-unit: {round(t.spacing.unit * space, 2)}px;",
        f"  --radius-sm: {r.sm}px;",
        f"  --radius-md: {r.md}px;",
        f"  --radius-lg: {r.lg}px;",
        f"  --shadow: {shadow};",
        f"  --border-width: {t.elevation.border_width}px;",
        f"  --max-width: {t.layout.max_width}px;",
        f"  --grid-columns: {t.layout.grid_columns};",
        f"  --gutter: {t.layout.gutter}px;",
        f"  --motion-duration: {t.motion.duration_ms}ms;",
        "}",
    ]
    default = "dark" if t.appearance == "dark" else "light"
    out = [
        f"/* {t.name} — generated by ArchitectFlow. Breakpoints: sm < "
        f"{t.layout.breakpoints.sm}px, md < {t.layout.breakpoints.md}px. */",
        *base,
    ]
    out += _css_block(":root", t, default)
    if t.appearance == "system":
        out += [
            "@media (prefers-color-scheme: dark) {",
            *["  " + line for line in _css_block(":root", t, "dark")],
            "}",
        ]
    out += _css_block('[data-theme="light"]', t, "light")
    out += _css_block('[data-theme="dark"]', t, "dark")
    if t.motion.respect_reduced_motion:
        out += [
            "@media (prefers-reduced-motion: reduce) {",
            "  :root { --motion-duration: 0ms; }",
            "}",
        ]
    return "\n".join(out) + "\n"


def design_spec(doc: ArchitectureDocument, title: str, revision: int) -> str:
    out = [f"# {title} — UI/UX design specification", "", f"Design revision {revision}.", ""]
    out += [*design_section(doc), "", *pages_section(doc), ""]
    out += ["## Component inventory", "", component_inventory(doc).strip()]
    return "\n".join(out) + "\n"


def page_flow(doc: ArchitectureDocument) -> str:
    pages = doc.design.pages
    ids = {p.id: ident(i, "p") for i, p in enumerate(pages)}
    lines = ["flowchart LR"]
    lines += [f'  {ids[p.id]}["{mermaid_label(f"{p.name} {p.route}")}"]' for p in pages]
    seen: set[tuple[str, str, str]] = set()
    for p in pages:
        for n, _ in walk(p.layout):
            inter = n.interaction
            if inter and inter.action == "navigate" and inter.target_page_id in ids:
                label = str(n.props.get("label", ""))
                key = (p.id, inter.target_page_id, label)
                if key in seen:
                    continue
                seen.add(key)
                style = "-->" if inter.implemented else "-.->"
                lines.append(
                    f'  {ids[p.id]} {style}|"{mermaid_label(label or "link")}"| '
                    f"{ids[inter.target_page_id]}"
                )
    for j in doc.design.journeys:
        steps = [s.page_id for s in j.steps if s.page_id in ids]
        for a, b in itertools.pairwise(steps):
            lines.append(f'  {ids[a]} ==>|"{mermaid_label(j.name)}"| {ids[b]}')
    return "\n".join(lines) + "\n"


def route_map(doc: ArchitectureDocument) -> str:
    roles = {a.id: a.name for a in doc.actors}
    rows = [
        {
            "route": p.route,
            "page": p.name,
            "parent": next((q.route for q in doc.design.pages if q.id == p.parent_id), None),
            "requires_auth": p.requires_auth,
            "roles": [roles.get(r, r) for r in p.roles],
            "states": [s.kind for s in p.states],
        }
        for p in sorted(doc.design.pages, key=lambda p: p.route)
    ]
    return json.dumps({"format": "architectflow-route-map", "routes": rows}, indent=2) + "\n"


def component_inventory(doc: ArchitectureDocument) -> str:
    usage: Counter[str] = Counter()
    where: dict[str, set[str]] = {}
    for p in doc.design.pages:
        for n, _ in walk(p.layout):
            usage[n.kind] += 1
            where.setdefault(n.kind, set()).add(p.route)
    out = ["| Component | Uses | Pages |", "|---|---|---|"]
    for kind, count in usage.most_common():
        out.append(f"| {kind} | {count} | {md_cell(', '.join(sorted(where[kind])))} |")
    return "\n".join(out) + "\n"
