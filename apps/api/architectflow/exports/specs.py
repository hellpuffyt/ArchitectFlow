from .text import md_cell, md_text

_SQL_TYPES = {
    "uuid": "uuid",
    "text": "text",
    "varchar": "varchar(255)",
    "integer": "integer",
    "bigint": "bigint",
    "numeric": "numeric",
    "boolean": "boolean",
    "date": "date",
    "timestamp": "timestamptz",
    "json": "jsonb",
    "bytes": "bytea",
}
_ON_DELETE = {"restrict": "RESTRICT", "cascade": "CASCADE", "set_null": "SET NULL"}


def _q(name: str) -> str:
    # Names are validated as [a-z_][a-z0-9_]*; quoting also avoids reserved words (e.g. "order").
    return '"' + name.replace('"', "") + '"'


def sql_ddl(doc: ArchitectureDocument) -> str:
    """PostgreSQL DDL. Foreign keys are added after all tables so order never matters."""
    ents = {e.id: e for e in doc.database.entities}
    out = [
        "-- Generated by ArchitectFlow from a saved design revision.",
        "-- Review before running: types, lengths and indexes are design-level choices.",
        "",
    ]
    for e in doc.database.entities:
        cols = []
        for f in e.fields:
            col = f"  {_q(f.name)} {_SQL_TYPES[f.type]}"
            if not f.nullable or f.primary_key:
                col += " NOT NULL"
            if f.unique and not f.primary_key:
                col += " UNIQUE"
            cols.append(col)
        pks = [f.name for f in e.fields if f.primary_key]
        if pks:
            cols.append(f"  PRIMARY KEY ({', '.join(_q(p) for p in pks)})")
        out.append(f"CREATE TABLE {_q(e.name)} (\n" + ",\n".join(cols) + "\n);")
        if e.description:
            safe = e.description.replace("'", "''")
            out.append(f"COMMENT ON TABLE {_q(e.name)} IS '{safe}';")
        out.append("")
    for e in doc.database.entities:
        for f in e.fields:
            fk = f.foreign_key
            if fk and fk.entity_id in ents:
                out.append(
                    f"ALTER TABLE {_q(e.name)} ADD CONSTRAINT "
                    f"{_q(f'fk_{e.name}_{f.name}'[:63])} FOREIGN KEY ({_q(f.name)}) "
                    f"REFERENCES {_q(ents[fk.entity_id].name)} ({_q(fk.field)}) "
                    f"ON DELETE {_ON_DELETE[fk.on_delete]};"
                )
    for e in doc.database.entities:
        for i, ix in enumerate(e.indexes):
            name = f"ix_{e.name}_{'_'.join(ix.fields)}"[:60] + (f"_{i}" if i else "")
            unique = "UNIQUE " if ix.unique else ""
            out.append(
                f"CREATE {unique}INDEX {_q(name)} ON {_q(e.name)} "
                f"({', '.join(_q(c) for c in ix.fields)});"
            )
    return "\n".join(out).rstrip() + "\n"


_OAS_TYPES: dict[str, dict[str, str]] = {
    "uuid": {"type": "string", "format": "uuid"},
    "text": {"type": "string"},
    "varchar": {"type": "string"},
    "integer": {"type": "integer", "format": "int32"},
    "bigint": {"type": "integer", "format": "int64"},
    "numeric": {"type": "number"},
    "boolean": {"type": "boolean"},
    "date": {"type": "string", "format": "date"},
    "timestamp": {"type": "string", "format": "date-time"},
    "json": {"type": "object"},
    "bytes": {"type": "string", "contentEncoding": "base64"},
}


def _schema(fields: list[ApiField]) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": {f.name: dict(_OAS_TYPES[f.type]) for f in fields},
        "required": [f.name for f in fields if f.required],
    }


def openapi(doc: ArchitectureDocument, title: str, revision: int) -> str:
    ents = {e.id: e for e in doc.database.entities}
    roles = {a.id: a.name for a in doc.actors}
    paths: dict[str, dict[str, Any]] = {}
    schemas: dict[str, Any] = {}
    for e in doc.database.entities:
        schemas[e.name] = {
            "type": "object",
            "properties": {f.name: dict(_OAS_TYPES[f.type]) for f in e.fields},
            "required": [f.name for f in e.fields if not f.nullable],
        }
    for ep in doc.api.endpoints:
        op: dict[str, Any] = {
            "operationId": re.sub(r"[^A-Za-z0-9_]", "_", ep.id),
            "summary": ep.summary or f"{ep.method} {ep.path}",
            "responses": {},
        }
        params = [
            {"name": p, "in": "path", "required": True, "schema": {"type": "string"}}
            for p in re.findall(r"{([A-Za-z0-9_]+)}", ep.path)
        ]
        params += [
            {"name": f, "in": "query", "required": False, "schema": {"type": "string"}}
            for f in ep.filters
        ]
        if ep.paginated:
            params += [
                {
                    "name": "limit",
                    "in": "query",
                    "required": False,
                    "schema": {"type": "integer", "minimum": 1, "maximum": 200},
                },
                {"name": "cursor", "in": "query", "required": False, "schema": {"type": "string"}},
            ]
        if params:
            op["parameters"] = params
        if ep.request_fields and ep.method in {"POST", "PUT", "PATCH"}:
            op["requestBody"] = {
                "required": True,
                "content": {"application/json": {"schema": _schema(ep.request_fields)}},
            }
        ent = ents.get(ep.response_entity_id or "")
        body: dict[str, Any] = (
            {"$ref": f"#/components/schemas/{ent.name}"} if ent else _schema(ep.response_fields)
        )
        if ep.response_is_list:
            body = {"type": "array", "items": body}
        ok = "201" if ep.method == "POST" else "200"
        op["responses"][ok] = {
            "description": "Success",
            "content": {"application/json": {"schema": body}},
        }
        for er in ep.errors:
            op["responses"][str(er.status)] = {"description": er.description}
        if ep.auth == "public":
            op["security"] = []
        if ep.auth == "roles":
            op["x-required-roles"] = [roles.get(r, r) for r in ep.roles]
        paths.setdefault(ep.path, {})[ep.method.lower()] = op
    spec = {
        "openapi": "3.1.0",
        "info": {
            "title": f"{title} API",
            "version": f"design-r{revision}",
            "description": "Generated by ArchitectFlow from a saved design revision. "
            "It describes intended behavior, not a running service.",
        },
        "paths": paths,
        "components": {
            "schemas": schemas,
            "securitySchemes": {"session": {"type": "apiKey", "in": "cookie", "name": "session"}},
        },
        "security": [{"session": []}],
    }
    return json.dumps(spec, indent=2) + "\n"


def tech_spec(doc: ArchitectureDocument, title: str, revision: int) -> str:
    labels = {n.id: n.label for n in doc.nodes}
    out = [
        f"# {md_text(title)} — technical specification",
        "",
        f"Design revision {revision}. Generated by ArchitectFlow.",
        "",
        "## Vision",
        "",
        md_text(doc.vision or "_No vision saved._"),
        "",
        "## Requirements",
        "",
    ]
    for kind in ("functional", "nonfunctional"):
        for r in getattr(doc.requirements, kind):
            out.append(f"- **{kind}** ({r.priority}, {r.status}) {md_text(r.text)}")
    out += [
        "",
        "## Architecture",
        "",
        "```mermaid",
        mermaid_flowchart(doc).rstrip(),
        "```",
        "",
        "| Component | Type | Technology | Replicas | Responsibility |",
        "|---|---|---|---|---|",
    ]
    for n in doc.nodes:
        t = NODE_TYPES[n.type].label if n.type in NODE_TYPES else n.type
        out.append(
            f"| {md_cell(n.label)} | {t} | {md_cell(n.technology)} | {n.replicas} | "
            f"{md_cell(n.description)} |"
        )
    out += ["", "| From | To | Protocol | Mode | Encrypted | Data |", "|---|---|---|---|---|---|"]
    for e in doc.edges:
        out.append(
            f"| {md_cell(labels.get(e.source, e.source))} | "
            f"{md_cell(labels.get(e.target, e.target))} | {md_cell(e.protocol)} | "
            f"{'sync' if e.synchronous else 'async'} | {e.encrypted} | "
            f"{md_cell(e.data)} |"
        )
    if doc.database.entities:
        out += ["", "## Data model", "", "```mermaid", erd(doc).rstrip(), "```"]
    if doc.api.endpoints:
        out += ["", "## API", "", "| Method | Path | Access | Summary |", "|---|---|---|---|"]
        for ep in doc.api.endpoints:
            out.append(
                f"| {ep.method} | `{md_cell(ep.path)}` | {ep.auth} | {md_cell(ep.summary)} |"
            )
    if doc.decisions:
        out += ["", "## Decisions", ""]
        out += [
            f"- **{md_text(d.title)}** ({d.status}): {md_text(d.rationale)} "
            f"Trade-offs: {md_text(d.tradeoffs)}"
            for d in doc.decisions
        ]
    findings = run_validation(doc)
    out += ["", f"## Validation ({len(findings)} findings)", ""]
    out += [f"- {f.severity}: {md_text(f.title)} — {md_text(f.evidence)}" for f in findings]
    if doc.open_questions:
        out += ["", "## Open questions", ""] + [f"- {md_text(q)}" for q in doc.open_questions]
    return "\n".join(out) + "\n"
